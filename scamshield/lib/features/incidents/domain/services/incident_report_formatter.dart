import '../entities/incident_record.dart';

/// Converts an incident into a plain-language report suitable for sharing.
///
/// The first report format is text so it works on every platform. A later
/// export service can render the same structured incident into PDF without
/// changing the underlying incident model.
class IncidentReportFormatter {
  const IncidentReportFormatter();

  String format(IncidentRecord incident) {
    final buffer = StringBuffer()
      ..writeln('SCAMSHIELD INCIDENT REPORT')
      ..writeln('Incident ID: ${incident.id}')
      ..writeln('Created: ${_formatDateTime(incident.createdAt)}')
      ..writeln('Status: ${_statusLabel(incident.status)}')
      ..writeln('Risk score: ${incident.riskScore}/100')
      ..writeln('Category: ${incident.category}')
      ..writeln('Source: ${incident.sourceLabel}');

    if (incident.sender.isNotEmpty) {
      buffer.writeln('Sender / account: ${incident.sender}');
    }
    if (incident.amount != null) {
      buffer.writeln('Amount involved: ${incident.amount}');
    }
    if ((incident.transactionReference ?? '').isNotEmpty) {
      buffer.writeln('Transaction reference: ${incident.transactionReference}');
    }

    buffer
      ..writeln()
      ..writeln('EVIDENCE / CONTENT')
      ..writeln(incident.content.isEmpty ? 'Not recorded.' : incident.content)
      ..writeln()
      ..writeln('WHY SCAMSHIELD FLAGGED IT');

    if (incident.reasons.isEmpty) {
      buffer.writeln('- No detailed warning reasons were recorded.');
    } else {
      for (final reason in incident.reasons) {
        buffer.writeln('- ${reason.title}: ${reason.explanation}');
      }
    }

    buffer
      ..writeln()
      ..writeln('RECOMMENDED ACTIONS');
    for (final action in incident.recommendedActions) {
      buffer.writeln('- $action');
    }

    if (incident.notes.isNotEmpty) {
      buffer
        ..writeln()
        ..writeln('USER NOTES')
        ..writeln(incident.notes);
    }

    buffer
      ..writeln()
      ..writeln('Generated by ScamShield. This report preserves the user-entered evidence and ScamShield risk assessment; it is not a police or bank reference number.');

    return buffer.toString();
  }

  String _formatDateTime(DateTime value) {
    String two(int number) => number.toString().padLeft(2, '0');
    return '${value.year}-${two(value.month)}-${two(value.day)} '
        '${two(value.hour)}:${two(value.minute)}';
  }

  String _statusLabel(IncidentStatus status) {
    switch (status) {
      case IncidentStatus.reviewing:
        return 'Reviewing';
      case IncidentStatus.actionRequired:
        return 'Action required';
      case IncidentStatus.reported:
        return 'Reported';
      case IncidentStatus.resolved:
        return 'Resolved';
    }
  }
}
